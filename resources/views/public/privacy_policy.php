                        <h5 class="fw-bold text-primary mt-4">2. Dados Pessoais Recolhidos</h5>
                        <p>No âmbito do programa de estágio e para a execução do plano pedagógico, são recolhidas as seguintes categorias de dados:</p>
                        <ul>
                            <li><strong>Dados de Identificação:</strong> Nome completo, nome social, data de nascimento, género, número do Bilhete de Identidade (BI).</li>
                            <li><strong>Dados de Contacto:</strong> Endereço de correio eletrónico, número de telefone e morada residencial.</li>
                            <li><strong>Dados Académicos:</strong> Instituição de ensino conveniada, curso, classe/nível de formação, número de processo e orientador escolar.</li>
                            <li><strong>Dados de Desempenho e Avaliação:</strong> Presenças, notas de tarefas, códigos/commits em repositórios GitHub, notas em testes e avaliações de competências.</li>
                            <li><strong>Dados de Localização Geográfica (GPS):</strong> Coordenadas pontuais de latitude, longitude e precisão capturadas exclusivamente no ato de marcação de ponto.</li>
                        </ul>

                        <h5 class="fw-bold text-primary mt-4">3. Finalidades do Tratamento e Base Legal</h5>
                        <p>
                            Os dados são tratados nos termos do Artigo 6.º e seguintes da <strong>Lei da Protecção de Dados Pessoais de Angola (Lei n.º 22/11)</strong>, com as seguintes finalidades:
                        </p>
                        <ol>
                            <li>Gestão e execução do contrato/acordo de estágio curricular e profissional.</li>
                            <li>Validação de assiduidade e pontualidade nas instalações da Asoftmedia.</li>
                            <li>Avaliação contínua de competências técnicas e comportamentais.</li>
                            <li>Emissão de declarações, relatórios e certificados oficiais de estágio com validação por QR Code.</li>
                            <li>Acompanhamento pedagógico e partilha de relatórios com as instituições de ensino parceiras.</li>
                        </ol>

                        <h5 class="fw-bold text-primary mt-4">4. Tratamento de Dados de Geolocalização (GPS) & Princípio da Minimização</h5>
                        <p>
                            Em estrita observância ao princípio da minimização da recolha de dados, o sistema <strong>NÃO realiza monitorização contínua nem rastreamento de localização do utilizador fora do momento exato do registo de presença</strong>. As coordenadas geográficas são processadas apenas no instante do Check-in/Check-out para cálculo matemático da distância em relação à sede da Asoftmedia (raio permitido de 100 metros) via Fórmula de Haversine.
                        </p>

                        <h5 class="fw-bold text-primary mt-4">5. Partilha e Destinatários dos Dados</h5>
                        <p>
                            Os dados pessoais não são comercializados a terceiros. Apenas têm acesso aos dados: (a) a equipa de Recursos Humanos e Administração da Asoftmedia; (b) os supervisores e orientadores técnicos designados; (c) a instituição de ensino de origem do estagiário, em modo de observador para fins de validação académica; e (d) entidades públicas ou judiciais quando exigido por lei.
                        </p>

                        <h5 class="fw-bold text-primary mt-4">6. Prazos de Conservação dos Dados</h5>
                        <p>
                            Os registos de estágio e históricos de certificação são conservados pelo período legalmente necessário para comprovação curricular e emissão de segundas vias de declarações, sendo eliminados ou anonimizados após o término dos prazos regulamentares aplicáveis.
                        </p>

                        <h5 class="fw-bold text-primary mt-4">7. Medidas de Segurança da Informação</h5>
                        <p>
                            A Asoftmedia aplica medidas técnicas e organizativas rigorosas, incluindo encriptação de senhas (bcrypt), tokens criptográficos SHA-256, isolamento em ambiente sandbox para personalizações de código, canais seguros HTTPS/TLS e auditoria detalhada de acessos.
                        </p>

                        <h5 class="fw-bold text-primary mt-4">8. Direitos dos Titulares dos Dados (Art. 18.º da Lei 22/11)</h5>
                        <p>
                            Nos termos da legislação angolana, o titular dos dados tem direito a solicitar:
                        </p>
                        <ul>
                            <li><strong>Direito de Informação e Acesso:</strong> Obter confirmação e cópia dos dados pessoais tratados.</li>
                            <li><strong>Direito de Rectificação:</strong> Solicitar a atualização ou correção de dados inexatos ou desatualizados.</li>
                            <li><strong>Direito de Eliminação / Cancelamento:</strong> Solicitar a eliminação dos dados quando cesse a finalidade ou a obrigação legal de guarda.</li>
                            <li><strong>Direito de Oposição:</strong> Opor-se a determinados tratamentos com base em motivos legítimos.</li>
                        </ul>
